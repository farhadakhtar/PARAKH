"""Build a calibration-ready dataset from whatever ``Data/`` actually holds.

Read-only over ``Data/``; every output lands in ``calibration_dataset/``. No
existing PARAKH module is imported or modified - this is a standalone tool.

What this run will find
-----------------------
``Data/`` contains two files, both generated by PARAKH itself:
``synthetic_dataset.csv`` and ``ground_truth_ledger.json``. There are no
ADSI tables, no district factsheets, and **no audit PDFs** - a repo-wide search
for ``*.pdf``, ``*.xlsx``, ``*.tsv`` and ``*.xml`` returns nothing.

That has one unavoidable consequence, and it is stated here rather than
discovered in the output: **step 3 has no input, so steps 4 and 5 produce no
labels.** The audit parser below is real and works; it simply has nothing to
parse today. Drop genuine CAG/PSU/SEAR PDFs into ``Data/`` and the same script
produces real labels with no edit.

Two things this tool refuses to do
----------------------------------
**It will not use the ground-truth ledger as audit labels.** The ledger records
*injected data-quality noise* - ``missing:vendor_name``,
``placeholder:date_approval``, ``date_order:approval_before_proposal``. None of
those is an overpayment, a ghost beneficiary, or a procurement irregularity.
Mapping them onto fraud categories would be fabrication. The ledger's own note
also says: *"NEVER join this into the corpus before Stage 7 evaluation - it
leaks labels."*

**It will not meet a target by inventing rows.** The brief asks for 200+
labelled records. With zero audit documents the honest count is zero, and the
report says so in those words.
"""

