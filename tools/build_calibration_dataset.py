def _year_of(value: Any) -> Optional[str]:
    """A four-digit year from any date-ish or FY-ish string."""
    text = _clean_text(value)
    if not text:
        return None
    match = re.search(r"(19|20)\d{2}", text)
    return match.group(0) if match else None


def attach_weak_labels(
    records: pd.DataFrame, audits: pd.DataFrame
) -> Tuple[pd.DataFrame, Dict[str, int]]:
    """Join audit observations onto records by geography, then year.

    Three tiers, most specific first:

    * **HIGH** - state, district and year all match.
    * **MEDIUM** - state and district match; year is absent or disagrees.
    * **LOW** - state matches only.

    A record with no audit coverage gets ``label = NULL``, never 0. Zero would
    assert "audited and found clean"; NULL says "never looked at", and the two
    are not the same claim. A 0 is only written where the record's own
    state-district **was** covered by at least one audit and this record was
    not among the findings.
    """
    labelled = records.copy()
    labelled["label"] = pd.NA
    labelled["confidence_label"] = pd.NA
    labelled["label_blocked_reason"] = pd.NA

    synthetic = labelled["source_file"].isin(NEVER_LABEL_SOURCES)
    if synthetic.any():
        labelled.loc[synthetic, "label_blocked_reason"] = (
            "synthetic record; a real audit cannot confirm a fictional work"
        )
    stats = {"high": 0, "medium": 0, "low": 0, "negative": 0, "unmatched": 0}

    if audits.empty or records.empty:
        stats["unmatched"] = len(labelled)
        return labelled, stats

    audits = audits.copy()
    exact: set = set()
    partial: set = set()
    loose: set = set()
    covered_cells: set = set()
    covered_states: set = set()

    for _, audit in audits.iterrows():
        state = _clean_text(audit.get("state"))
        district = _clean_text(audit.get("district"))
        if state and state != UNKNOWN:
            covered_states.add(state.lower())
            if district and district != UNKNOWN:
                covered_cells.add((state.lower(), district.lower()))

    # Lowercased on both sides: the same state arrives as "JHARKHAND" from
    # one source file and "Jharkhand" from another, and they are one place.
    record_state = labelled["state"].map(lambda v: (_clean_text(v) or "").lower())
    record_district = labelled["district"].map(lambda v: (_clean_text(v) or "").lower())
    record_year = labelled["financial_year"].map(_year_of)

    for position, audit in audits.iterrows():
        state = (_clean_text(audit.get("state")) or "").lower()
        district = (_clean_text(audit.get("district")) or "").lower()
        year = _year_of(audit.get("financial_year"))
        if year and str(audit.get("financial_year")).strip() == UNKNOWN:
            year = None
        if not state or state == UNKNOWN.lower():
            continue
        in_state = record_state == state
        if district and district != UNKNOWN.lower():
            in_cell = in_state & (record_district == district)
            if year:
                hit = in_cell & (record_year == year)
                exact.update(labelled.index[hit])
            partial.update(labelled.index[in_cell])
        else:
            loose.update(labelled.index[in_state])

    partial -= exact
    loose -= exact | partial

    # Applied after matching rather than before, so the report can state how
    # many labels the rule withheld instead of hiding the exclusion.
    blocked = set(labelled.index[synthetic])
    stats["blocked_synthetic"] = len(
        (exact | partial | loose) & blocked
    )
    exact -= blocked
    partial -= blocked
    loose -= blocked

    for indices, tier in ((exact, "HIGH"), (partial, "MEDIUM"), (loose, "LOW")):
        if indices:
            selection = sorted(indices)
            labelled.loc[selection, "label"] = 1
            labelled.loc[selection, "confidence_label"] = tier
            stats[tier.lower()] = len(selection)

    # Negatives: inside an audited state-district, but not among its findings.
    positive = labelled["label"].notna()
    in_covered = pd.Series(
        [
            (s, d) in covered_cells
            for s, d in zip(record_state, record_district)
        ],
        index=labelled.index,
    )
    negatives = in_covered & ~positive & ~synthetic
    labelled.loc[negatives, "label"] = 0
    labelled.loc[negatives, "confidence_label"] = "MEDIUM"
    stats["negative"] = int(negatives.sum())
    stats["unmatched"] = int(labelled["label"].isna().sum())
    return labelled, stats


