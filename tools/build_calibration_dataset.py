def _normalise_key(name: str) -> str:
    """Lowercase and strip non-alphanumerics, for synonym matching."""
    return re.sub(r"[^a-z0-9]", "", str(name).lower())


def _clean_text(value: Any) -> Optional[str]:
    """Collapse whitespace; return None for anything empty."""
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return None
    text = unicodedata.normalize("NFKC", str(value)).strip()
    text = re.sub(r"\s+", " ", text)
    return text or None


def _parse_amount(match: re.Match) -> Optional[float]:
    """Turn a matched rupee expression into a float number of rupees."""
    raw, unit = match.group(1), (match.group(2) or "").lower().rstrip(".")
    try:
        value = float(raw.replace(",", ""))
    except ValueError:
        return None
    if unit:
        return value * AMOUNT_MULTIPLIER[unit]
    # No unit. A bare "Rs 1" is a table artefact or a column header, not a
    # finding - audit reports do not report single-rupee irregularities. Below
    # a thousand rupees the number is discarded rather than recorded as a
    # magnitude nobody should trust.
    return value if value >= 1000 else None


