#: Issue vocabulary. Ordered: the first pattern that matches wins, so the more
#: specific categories are checked before the vaguer ones.
ISSUE_PATTERNS: Tuple[Tuple[str, str], ...] = (
    ("ghost beneficiary",
     r"ghost\s+(?:beneficiar|worker|employee|muster)|"
     r"fictitious\s+(?:beneficiar|name|worker)|"
     r"non-?existent\s+beneficiar"),
    ("overpayment",
     r"over-?payment|excess\s+payment|paid\s+in\s+excess|"
     r"overcharg|inflated\s+(?:bill|rate|cost)|double\s+payment"),
    ("procurement irregularity",
     r"procurement\s+irregular|tender(?:ing)?\s+irregular|"
     r"without\s+(?:inviting\s+)?tender|single\s+tender|"
     r"violation\s+of\s+(?:the\s+)?(?:gfr|procurement)|favouritism"),
    ("underutilization",
     r"under-?utilis|under-?utiliz|unspent\s+balance|funds?\s+(?:lying|remained)\s+"
     r"(?:idle|unspent)|non-?utilis|savings?\s+not\s+surrendered"),
    ("delay",
     r"\bdelay(?:ed|s)?\b|time\s+over-?run|not\s+completed\s+within|"
     r"belated|inordinate\s+delay"),
)

SEVERITY_PATTERNS: Tuple[Tuple[str, str], ...] = (
    ("HIGH",
     r"fraud|misappropriat|embezzl|siphon|fictitious|forged|"
     r"criminal|malafide|serious\s+irregular|major\s+loss"),
    ("MEDIUM",
     r"irregular|avoidable|undue\s+(?:favour|benefit)|deficien|lapse|"
     r"non-?compliance|shortfall"),
    ("LOW", r"minor|procedural|clerical|technical\s+observation"),
)

#: Rupee amounts as Indian audit reports write them: "Rs. 12.45 crore",
#: "₹ 3,45,678", "Rs 5.2 lakh". The multiplier is applied so every amount is
#: stored in rupees.
AMOUNT_PATTERN = re.compile(
    r"(?:rs\.?|inr|₹)\s*([0-9][0-9,]*(?:\.[0-9]+)?)\s*"
    r"(crore|cr\b|lakh|lac\b|million|thousand)?",
    re.IGNORECASE,
)
AMOUNT_MULTIPLIER = {
    "crore": 10_000_000, "cr": 10_000_000,
    "lakh": 100_000, "lac": 100_000,
    "million": 1_000_000, "thousand": 1_000,
}

AUDIT_COLUMNS: Tuple[str, ...] = (
    "audit_id", "state", "state_source", "district", "financial_year",
    "scheme", "issue_type", "severity", "amount", "source_pdf",
)

UNKNOWN = "UNKNOWN"

#: Source files whose records may never carry a label. These are PARAKH's own
#: generated corpus: the works are fictional, so no real audit finding can
#: confirm or clear one. Today none of them matches an audit geography, but
#: that is luck - a future audit report naming Gujarat would label thousands
#: of invented library buildings as "audit issue present". Excluded by rule,
#: not left to coincidence.
NEVER_LABEL_SOURCES = frozenset({"synthetic_dataset.csv"})


