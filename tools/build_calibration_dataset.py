def classify_file(path: Path) -> Tuple[str, bool, str]:
    """Classify one file.

    Returns:
        ``(type, usable, reason)``. ``usable`` means this tool can extract
        something from it, not that the content is good.
    """
    name = path.name
    lowered = name.lower()
    suffix = path.suffix.lower()

    if any(marker in lowered for marker in NOISE_MARKERS) or name.startswith("."):
        return "NOISE", False, "temporary, hidden or editor lock file"
    if suffix in AUDIT_SUFFIXES:
        if any(marker in lowered for marker in AUDIT_NAME_MARKERS):
            return "AUDIT_REPORTS", True, "PDF whose name marks it an audit report"
        return "AUDIT_REPORTS", True, "PDF; name carries no audit marker, parsed anyway"
    if suffix in STRUCTURED_SUFFIXES:
        return "STRUCTURED_DATA", True, f"tabular {suffix} file"
    if suffix in SEMI_STRUCTURED_SUFFIXES:
        # Readable, but only tabular records feed the normalised table. A
        # ledger of injected defects is not calibration input; saying so here
        # is more useful than silently ignoring the file.
        return (
            "SEMI_STRUCTURED",
            False,
            f"{suffix} read for provenance only; not a source of records "
            "(see report.md)",
        )
    return "NOISE", False, f"unrecognised format {suffix or '(none)'}"


def discover(data_dir: Path) -> pd.DataFrame:
    """Index every file under ``data_dir``."""
    rows: List[Dict[str, Any]] = []
    if not data_dir.exists():
        return pd.DataFrame(columns=["file_name", "type", "usable", "reason"])
    for path in sorted(data_dir.rglob("*")):
        if not path.is_file():
            continue
        kind, usable, reason = classify_file(path)
        rows.append(
            {
                "file_name": str(path.relative_to(data_dir)).replace("\\", "/"),
                "type": kind,
                "usable": usable,
                "reason": reason,
                "size_bytes": path.stat().st_size,
            }
        )
    return pd.DataFrame(rows, columns=["file_name", "type", "usable", "reason",
                                       "size_bytes"])


