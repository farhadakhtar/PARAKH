def _read_table(path: Path) -> Tuple[Optional[pd.DataFrame], Optional[str]]:
    """Read a table, trying encodings in order. Never raises.

    Returns:
        ``(frame, error)``. Exactly one is None.
    """
    suffix = path.suffix.lower()
    try:
        if suffix in {".xlsx", ".xls"}:
            return pd.read_excel(path, dtype=str), None
        separator = "\t" if suffix == ".tsv" else ","
        last: Optional[Exception] = None
        for encoding in ("utf-8", "utf-8-sig", "cp1252", "latin-1"):
            try:
                return (
                    pd.read_csv(
                        path,
                        dtype=str,
                        sep=separator,
                        encoding=encoding,
                        keep_default_na=False,
                        na_values=[""],
                        on_bad_lines="warn",
                    ),
                    None,
                )
            except UnicodeDecodeError as exc:
                last = exc
                continue
        return None, f"undecodable with any tried encoding ({last})"
    except Exception as exc:  # noqa: BLE001 - a malformed file must not crash the run
        return None, f"{type(exc).__name__}: {exc}"


def normalise_table(frame: pd.DataFrame, source: str) -> pd.DataFrame:
    """Map an arbitrary table onto the normalised schema.

    Missing columns become NULL; **no row is ever dropped** and no value is
    coerced beyond a numeric parse that falls back to NULL. The point is a
    faithful re-shaping, not a cleaning.
    """
    mapping: Dict[str, str] = {}
    for column in frame.columns:
        target = COLUMN_SYNONYMS.get(_normalise_key(column))
        # First writer wins, so an earlier, more canonical column is not
        # overwritten by a later synonym.
        if target and target not in mapping.values():
            mapping[column] = target

    out = pd.DataFrame(index=frame.index)
    for target in NORMALISED_COLUMNS:
        if target == "source_file":
            out[target] = source
            continue
        origin = next((c for c, t in mapping.items() if t == target), None)
        out[target] = frame[origin] if origin is not None else None

    for numeric in ("budget_allocated", "expenditure"):
        out[numeric] = pd.to_numeric(out[numeric], errors="coerce")

    # DELIBERATE DEVIATION from "missing column -> NULL". Where no year column
    # exists but a date does, the year is READ from that date rather than left
    # blank. This is extraction, not invention: the value is already in the
    # row. It matters because step 4's HIGH-confidence tier needs a year, and
    # without this every match would degrade to MEDIUM. The source column used
    # is recorded so the derivation is never mistaken for a declared field.
    blank_year = out["financial_year"].isna()
    if blank_year.any():
        for candidate in ("date_proposal", "date_sanction", "date_approval",
                          "sanction_date", "date"):
            origin = next(
                (c for c in frame.columns if _normalise_key(c) == _normalise_key(candidate)),
                None,
            )
            if origin is None:
                continue
            derived = frame.loc[blank_year, origin].map(
                lambda value: (
                    match.group(0)
                    if (match := re.search(r"(19|20)\d{2}", str(value)))
                    else None
                )
            )
            out.loc[blank_year, "financial_year"] = derived
            out.loc[blank_year & out["financial_year"].notna(), "year_source"] = origin
            blank_year = out["financial_year"].isna()
            if not blank_year.any():
                break
    if "year_source" not in out.columns:
        out["year_source"] = None

    # A record_id is required downstream. Where the source has none, a
    # positional id is minted and marked as such - inventing a business key
    # would be worse than admitting there is none.
    missing_id = out["record_id"].isna()
    if missing_id.any():
        out.loc[missing_id, "record_id"] = [
            f"{Path(source).stem}#row{position}"
            for position in out.index[missing_id]
        ]
    return out[list(NORMALISED_COLUMNS) + ["year_source"]]


def build_normalised(index: pd.DataFrame, data_dir: Path) -> Tuple[pd.DataFrame, List[str]]:
    """Normalise every usable structured file."""
    frames: List[pd.DataFrame] = []
    notes: List[str] = []
    structured = index[(index["type"] == "STRUCTURED_DATA") & index["usable"]]
    for name in structured["file_name"]:
        path = data_dir / name
        frame, error = _read_table(path)
        if frame is None:
            notes.append(f"{name}: unreadable - {error}")
            continue
        frames.append(normalise_table(frame, name))
        notes.append(f"{name}: {len(frame):,} row(s) normalised")
    if not frames:
        return pd.DataFrame(columns=list(NORMALISED_COLUMNS)), notes
    return pd.concat(frames, ignore_index=True), notes


